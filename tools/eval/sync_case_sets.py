#!/usr/bin/env python3
"""Case-set consistency for D1-eval.

Enforces:
  1. Every case file's `category` equals its parent directory name.
  2. Every suite (_*.yaml) references only existing case ids.
  3. Every case file is referenced by at least one suite (unless quarantine).

Usage:
  python3 tools/eval/sync_case_sets.py --check   # exit 0 = consistent
  python3 tools/eval/sync_case_sets.py --write   # rewrite suites from case list
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import yaml

REPO_ROOT = Path(__file__).resolve().parent.parent.parent
CASES_DIR = REPO_ROOT / "eval" / "cases"


def load_all_cases(cases_dir: Path) -> dict[str, dict]:
    """id -> {path, category, quarantine} for all non-suite cases."""
    cases: dict[str, dict] = {}
    for path in sorted(cases_dir.rglob('*.yaml')):
        if path.name.startswith('_'):
            continue
        data = yaml.safe_load(path.read_text(encoding='utf-8'))
        if not isinstance(data, dict) or 'id' not in data:
            print(f"FAIL {path}: missing 'id'", file=sys.stderr)
            continue
        cases[data['id']] = {
            'path': path,
            'category': data.get('category', ''),
            'quarantine': data.get('quarantine', False),
        }
    return cases


def load_suites(cases_dir: Path) -> dict[str, dict]:
    suites: dict[str, dict] = {}
    for path in sorted(cases_dir.glob('_*.yaml')):
        data = yaml.safe_load(path.read_text(encoding='utf-8'))
        if isinstance(data, dict) and isinstance(data.get('cases'), list):
            suites[path.name] = {'path': path, 'ids': data['cases']}
    return suites


def check(cases_dir: Path) -> bool:
    ok = True
    cases = load_all_cases(cases_dir)
    suites = load_suites(cases_dir)

    # 1. category == directory name.
    for cid, info in cases.items():
        expected_cat = info['path'].parent.name
        if info['category'] != expected_cat:
            print(f"FAIL {info['path']}: category '{info['category']}' != dir '{expected_cat}'")
            ok = False

    # 2. suite ids exist.
    all_ids = set(cases)
    for sname, suite in suites.items():
        missing = [i for i in suite['ids'] if i not in all_ids]
        if missing:
            print(f"FAIL {sname}: missing case ids {missing}")
            ok = False

    # 3. every non-quarantine case referenced by a suite.
    referenced = set()
    for suite in suites.values():
        referenced.update(suite['ids'])
    unreferenced = [cid for cid, info in cases.items()
                    if cid not in referenced and not info['quarantine']]
    if unreferenced:
        print(f"FAIL: cases not in any suite: {unreferenced}")
        ok = False

    if ok:
        print(f"OK: {len(cases)} cases, {len(suites)} suites consistent")
    return ok


def write(cases_dir: Path) -> bool:
    """Rewrite _nightly.yaml from the current case files (smoke stays curated)."""
    cases = load_all_cases(cases_dir)
    nightly = cases_dir / '_nightly.yaml'
    ids = sorted(cases.keys())
    content = ("# Auto-generated by sync_case_sets.py --write. Do not edit manually.\n"
               "# Nightly: full regression set (all cases).\n"
               "cases:\n")
    content += "".join(f"  - {i}\n" for i in ids)
    nightly.write_text(content, encoding='utf-8')
    print(f"wrote _nightly.yaml: {len(ids)} cases")
    return True


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='validate consistency (exit 0=OK)')
    parser.add_argument('--write', action='store_true', help='rewrite suites from cases')
    args = parser.parse_args()
    if args.write:
        return 0 if write(CASES_DIR) else 1
    return 0 if check(CASES_DIR) else 1


if __name__ == '__main__':
    sys.exit(main())
